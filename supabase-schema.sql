-- Pagode do Lukinha — schema idempotente
-- Pode ser executado novamente sem apagar dados existentes.

create table if not exists public.site_settings (
  id text primary key default 'main',
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz default now()
);

create table if not exists public.shows (
  id bigint generated by default as identity primary key,
  show_date date not null,
  show_time time,
  city text not null,
  state text,
  event_name text,
  place text,
  ticket_url text,
  published boolean default true,
  created_at timestamptz default now()
);

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text,
  youtube_url text not null,
  description text,
  published boolean default true,
  sort_order int default 0,
  created_at timestamptz default now()
);

-- Garante colunas necessárias mesmo se as tabelas já existiam em versão anterior.
alter table public.site_settings add column if not exists data jsonb not null default '{}'::jsonb;
alter table public.site_settings add column if not exists updated_at timestamptz default now();

alter table public.shows add column if not exists show_date date;
alter table public.shows add column if not exists show_time time;
alter table public.shows add column if not exists city text;
alter table public.shows add column if not exists state text;
alter table public.shows add column if not exists event_name text;
alter table public.shows add column if not exists place text;
alter table public.shows add column if not exists ticket_url text;
alter table public.shows add column if not exists published boolean default true;
alter table public.shows add column if not exists created_at timestamptz default now();

