-- PostgreSQL não possui CREATE POLICY IF NOT EXISTS.
-- Estes blocos só criam cada policy quando ela ainda não existe.
do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='site_settings' and policyname='public read settings') then
    create policy "public read settings" on public.site_settings for select to anon, authenticated using (true);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='shows' and policyname='public read shows') then
    create policy "public read shows" on public.shows for select to anon, authenticated using (published = true);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='videos' and policyname='public read videos') then
    create policy "public read videos" on public.videos for select to anon, authenticated using (published = true);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='site_settings' and policyname='auth manage settings') then
    create policy "auth manage settings" on public.site_settings for all to authenticated using (true) with check (true);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='shows' and policyname='auth manage shows') then
    create policy "auth manage shows" on public.shows for all to authenticated using (true) with check (true);
  end if;

  if not exists (select 1 from pg_policies where schemaname='public' and tablename='videos' and policyname='auth manage videos') then
    create policy "auth manage videos" on public.videos for all to authenticated using (true) with check (true);
  end if;
end $$;

